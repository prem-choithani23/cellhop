# PROJECT     : CellHop Planner
# WHAT IT IS  : The geometry engine for hexagonal cellular layouts. It knows how
#               (i, j) -> cluster size N, where every hexagon centre is, which
#               frequency-group each cell gets, and where the co-channel cells are.
# WHAT IT DOES: * cluster_size(i, j)        N = i^2 + i*j + j^2
#               * valid_cluster_sizes()     list of all legal (N, i, j)
#               * axial_to_xy()             hex-grid coordinates -> x,y in km
#               * assign_labels()           colours cells so equal colours = same frequencies
#               * first_tier_cochannel()    the 6 nearest co-channel cell centres
#               * hex_vertices()            corner points for drawing a hexagon
# LAST STEP   : config/settings.py defined (i, j) pairs and cell area (not used here yet).
# NEXT STEP   : wcn/exp1_frequency_reuse.py draws maps and measures D with these
#               functions; wcn/integrated_planner.py reuses the geometry for SIR.
# MATHS NOTE  : Hex cells use oblique axes u,v at 60 degrees. Centre of cell (a,b)
#               is  a*u + b*v  with |u| = |v| = sqrt(3)*R  (R = hexagon circumradius).
#               Co-channel cell = i*u + j*v  =>  D = sqrt(3*N)*R.
# =============================================================================

import math                      # math: sqrt, cos, sin, pi for scalar maths
import numpy as np               # numpy: arrays for vertex coordinates

SQRT3 = math.sqrt(3.0)           # sqrt(3) appears everywhere in hexagon geometry


def cluster_size(i, j):
    """Return N = i^2 + i*j + j^2 for non-negative integer shifts (i, j)."""
    if i < 0 or j < 0:                        # shifts must be non-negative integers
        raise ValueError("i and j must be non-negative")
    if i == 0 and j == 0:                     # (0,0) would mean no shift at all
        raise ValueError("i and j cannot both be zero")
    return i * i + i * j + j * j              # the hexagonal 'Fermat' formula


def valid_cluster_sizes(min_n=1, max_n=25):
    """List every legal cluster size between min_n and max_n as tuples (N, i, j)."""
    found = {}                                # dict N -> (i, j); keeps one pair per N
    for i in range(0, 12):                    # try shifts i = 0..11
        for j in range(0, i + 1):             # j <= i avoids duplicates (i,j) vs (j,i)
            if i == 0 and j == 0:             # skip the invalid (0,0)
                continue
            n = cluster_size(i, j)            # compute N
            if min_n <= n <= max_n and n not in found:
                found[n] = (i, j)             # remember the first pair that gives this N
    return [(n, *found[n]) for n in sorted(found)]   # sorted list of (N, i, j)


def cell_radius_from_area(area_km2):
    """Hexagon area = (3*sqrt(3)/2) R^2  ->  R = sqrt(2*Area / (3*sqrt(3)))."""
    return math.sqrt(2.0 * area_km2 / (3.0 * SQRT3))


def axial_to_xy(a, b, R):
    """Convert axial hex coordinates (a along u, b along v) to Cartesian x, y."""
    x = SQRT3 * R * (a + b / 2.0)             # x = sqrt(3) R (a + b/2)
    y = 1.5 * R * b                           # y = 1.5 R b
    return x, y


def hex_distance(a, b):
    """Number of cell-steps from the origin to axial cell (a, b)."""
    return max(abs(a), abs(b), abs(a + b))    # standard hex-grid distance formula


def hex_disc(radius):
    """All axial cells within `radius` steps of the origin (a filled hexagonal patch)."""
    cells = []                                # list that will hold (a, b) tuples
    for a in range(-radius, radius + 1):      # scan a-axis
        for b in range(-radius, radius + 1):  # scan b-axis
            if hex_distance(a, b) <= radius:  # keep only cells inside the disc
                cells.append((a, b))
    return cells


def disc_radius_for(n_cells_needed, min_radius=2):
    """Smallest disc radius whose cell count 3r(r+1)+1 is >= n_cells_needed."""
    r = min_radius                            # start from a sensible minimum
    while 3 * r * (r + 1) + 1 < n_cells_needed:   # a hex disc of radius r has 3r(r+1)+1 cells
        r += 1                                # grow until it is big enough
    return r


def assign_labels(cells, i, j):
    """
    Give each cell a frequency-group index 0..N-1 so that all cells with the same index
    are co-channel cells (identical colour in the plots).

    Idea: the co-channel cells form a lattice generated by w1 = (i, j) and its 60-degree
    rotation w2 = (-j, i+j). Two cells share a group iff their difference is an integer
    combination of w1 and w2. Solving that 2x2 system gives integer 'numerators' mod N.
    """
    n = cluster_size(i, j)                    # cluster size N (= determinant of the lattice)
    keys = {}                                 # cell -> (key1, key2) coset key
    for (a, b) in cells:
        k1 = (a * (i + j) + j * b) % n        # numerator of coefficient s (mod N)
        k2 = (i * b - j * a) % n              # numerator of coefficient t (mod N)
        keys[(a, b)] = (k1, k2)
    unique = sorted(set(keys.values()))       # sorted -> key (0,0) first -> origin gets label 0
    index = {key: idx for idx, key in enumerate(unique)}   # coset key -> label number
    return {cell: index[key] for cell, key in keys.items()}


def first_tier_cochannel(i, j, R):
    """
    Centres (x, y) of the six nearest co-channel cells around the origin cell.
    Start with the vector w1 = (i, j) and rotate it by 60 degrees five times.
    Rotation by 60 deg in axial coordinates:  (a, b) -> (-b, a + b).
    """
    a, b = i, j                               # first co-channel cell (axial coordinates)
    centres = []                              # will hold six (x, y) pairs
    for _ in range(6):                        # six rotations of 60 degrees = full circle
        centres.append(axial_to_xy(a, b, R))  # store its Cartesian position
        a, b = -b, a + b                      # rotate (a, b) by +60 degrees
    return centres


def hex_vertices(cx, cy, R):
    """Six corner points of a pointy-top hexagon of circumradius R centred at (cx, cy)."""
    angles = np.deg2rad(30.0 + 60.0 * np.arange(6))   # corners at 30, 90, 150, ... degrees
    xs = cx + R * np.cos(angles)              # x coordinates of the corners
    ys = cy + R * np.sin(angles)              # y coordinates of the corners
    return np.column_stack([xs, ys])          # shape (6, 2) array ready for a Polygon


def reference_cluster(cells, labels, R):
    """
    Pick one compact cluster of N cells: for each label, the cell nearest to the origin.
    (Those cells lie in the Wigner-Seitz region of the co-channel lattice = a valid cluster.)
    """
    best = {}                                 # label -> (distance, cell)
    for cell in cells:
        x, y = axial_to_xy(*cell, R)          # position of this cell
        d = math.hypot(x, y)                  # distance from the origin
        lab = labels[cell]
        # keep the nearest cell; tie-break on coordinates to stay deterministic
        if lab not in best or (d, cell) < best[lab][:2]:
            best[lab] = (d, cell)
    return [v[1] for v in best.values()]      # list of N cells forming the reference cluster
